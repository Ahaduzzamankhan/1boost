#[cfg(test)]
mod tests {
    use super::*;
    use crate::delta;

    #[test]
    fn reuses_the_payload_version_comparison() {
        assert!(is_newer("1.3.2", "1.3.1"));
        assert!(!is_newer("1.3.1", "1.3.1"));
    }

    #[test]
    fn reports_the_mode_it_installed_from() {
        assert_eq!(Mode::Delta.as_str(), "delta");
        assert_eq!(Mode::Full.as_str(), "full");
    }

    #[test]
    fn builds_the_delta_url_next_to_the_full_payload() {
        // The patch must be fetched from the release the signed manifest named,
        // so the URL is derived from the payload's own URL.
        let payload_url = "https://github.com/Ahaduzzamankhan/1boost/releases/download/v1.3.2/1Boost_1.3.2_x64-setup.nsis.zip";
        let (dir, _) = payload_url.rsplit_once('/').unwrap();
        let url = format!("{dir}/{}", payload::delta_asset_name("1.3.1", "1.3.2"));
        assert_eq!(
            url,
            "https://github.com/Ahaduzzamankhan/1boost/releases/download/v1.3.2/1Boost_1.3.2_x64-setup.from-1.3.1.1bdelta"
        );
    }

    #[test]
    fn refuses_a_payload_that_is_not_an_installer_archive() {
        assert!(extract_installer(b"not a zip file").is_none());
        assert!(extract_installer(&[]).is_none());
    }

    #[test]
    fn round_trips_the_fixture_through_the_public_delta_api() {
        // Guards the wiring the updater uses, not just the format.
        let base = include_bytes!("delta_fixtures/base.bin");
        let target = include_bytes!("delta_fixtures/target.bin");
        let patch = include_bytes!("delta_fixtures/patch.1bdelta");
        assert_eq!(delta::rebuild(patch, base).unwrap(), target);
    }
}